import type { Quiz, Weights } from '../src/types';
import {
  THRESHOLDS,
  checkPointBudgets,
  checkTimeLimits,
  findLockIns,
  measureCoverage,
  measureInfluence,
  measureProfiles,
  measureStability,
  type Flag,
} from './detectors';
import type { Simulation } from './simulate';

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

export interface Audit {
  flags: Flag[];
  markdown: string;
}

/** Runs every detector and renders one Markdown report. Deterministic: same input, same bytes. */
export function buildReport(quiz: Quiz, weights: Weights, sim: Simulation, name: string): Audit {
  const influence = measureInfluence(sim);
  const lockIns = findLockIns(sim);
  const coverage = measureCoverage(sim);
  const profiles = measureProfiles(sim);
  const stability = measureStability(sim);
  const budgets = checkPointBudgets(quiz);
  const limits = checkTimeLimits(quiz);

  const flags = [
    ...influence.flags,
    ...lockIns.flags,
    ...coverage.flags,
    ...profiles.flags,
    ...stability.flags,
    ...budgets.flags,
    ...limits.flags,
  ];
  const n = sim.outcomes.length;
  const sectionFlags = (f: Flag[]) => (f.length ? f.map((x) => `> ⚠️ ${x.message}`).join('\n>\n') : '> ✅ nothing to flag.');

  const md = [
    `# audit: \`${name}\` weights`,
    '',
    `Generated by \`pnpm audit:engine${name === 'default' ? '' : ` --weights ${name}`}\`. ` +
      `Every combination of emotion and answers was run through the engine: **${n.toLocaleString('en-US')} combos**, ` +
      `${stability.stats.pairs.toLocaleString('en-US')} single-answer changes.`,
    '',
    `Weights: emotion × ${weights.emotion}, ` +
      `questions ${Object.keys(weights.questions).length ? Object.entries(weights.questions).map(([q, w]) => `${q} × ${w}`).join(', ') + ', others × 1' : 'all × 1'}, ` +
      `craving bonus +${weights.cravingBonus}.`,
    '',
    '## summary',
    '',
    flags.length ? `**${flags.length} flag(s).**\n\n${flags.map((f) => `- **${f.check}** — ${f.message}`).join('\n')}` : '**No flags.** ✅',
    '',
    '## 1. influence',
    '',
    'Two questions per source. *Flips #1*: change only this answer, how often does the #1 dish change? ' +
      '*Explains*: how much does knowing this answer alone tell you about the result ' +
      "(mutual information as a share of the outcome's entropy; 0% = nothing, 100% = everything). " +
      `Flagged if one source explains more than ${pct(THRESHOLDS.dominant)} of the #1 dish or the profile, ` +
      `or less than ${pct(THRESHOLDS.decoration)} of the #1 dish.`,
    '',
    table(
      ['source', 'flips #1', 'explains #1', 'explains profile'],
      influence.rows.map((r) => [
        `\`${r.source}\``,
        pct(r.flipRate),
        `${pct(r.explainsTop)} ${bar(r.explainsTop / THRESHOLDS.dominant)}`,
        `${pct(r.explainsProfile)} ${bar(r.explainsProfile / THRESHOLDS.dominant)}`,
      ]),
    ),
    '',
    sectionFlags(influence.flags),
    '',
    '## 2. lock-in',
    '',
    `For each answer: the item that wins most often when it's picked. Flagged above ${pct(THRESHOLDS.lockIn)}. Top 10 shown.`,
    '',
    table(
      ['answer', 'most common #1', 'share'],
      [...lockIns.rows]
        .sort((a, b) => b.share - a.share)
        .slice(0, 10)
        .map((r) => [`\`${r.source}=${r.option}\``, `\`${r.item}\``, pct(r.share)]),
    ),
    '',
    sectionFlags(lockIns.flags),
    '',
    '## 3. coverage',
    '',
    `Every item should reach #1 for *someone*. Fair share of #1s is ${pct(1 / sim.itemIds.length)}; flagged above ${THRESHOLDS.hogShare}× that.`,
    '',
    table(
      ['item', '#1', 'in top 3'],
      coverage.rows.map((r) => [`\`${r.item}\``, `${r.firsts} (${pct(r.firsts / n)})`, `${r.appearances} (${pct(r.appearances / n)})`]),
    ),
    '',
    sectionFlags(coverage.flags),
    '',
    '## 4. profiles',
    '',
    `Evenness (normalised entropy, 1 = perfectly even): **${profiles.entropy.toFixed(2)}**. ` +
      `Flagged if a profile is unreachable or above ${THRESHOLDS.profileSkew}× the uniform ${pct(1 / sim.profileIds.length)}.`,
    '',
    table(
      ['profile', 'people', 'share'],
      profiles.rows.map((r) => [`\`${r.profile}\``, r.count, `${pct(r.share)} ${bar(r.share * sim.profileIds.length / THRESHOLDS.profileSkew)}`]),
    ),
    '',
    sectionFlags(profiles.flags),
    '',
    '## 5. stability',
    '',
    'Change one answer, keep the rest. A good engine moves a little: not nothing (answers would be decoration), not everything (answers would be a slot machine).',
    '',
    table(
      ['metric', 'value'],
      [
        ['mean items kept in top 3', `${stability.stats.meanOverlap.toFixed(2)} / 3`],
        ['top 3 identical', pct(stability.stats.identical)],
        ['#1 changes', pct(stability.stats.firstChanged)],
        ['whole top 3 replaced', pct(stability.stats.fullyReplaced)],
      ],
    ),
    '',
    `Flagged as jumpy above ${pct(THRESHOLDS.jumpy)} fully replaced, sticky above ${pct(THRESHOLDS.sticky)} identical.`,
    '',
    sectionFlags(stability.flags),
    '',
    '## 6. data checks',
    '',
    `Point budgets: every option within a question should hand out the same points (±${pct(THRESHOLDS.budgetDrift)}).`,
    '',
    sectionFlags(budgets.flags),
    '',
    `Time limits: each should leave at least ${THRESHOLDS.minEligible} items.`,
    '',
    table(['limit', 'items left'], limits.rows.map((r) => [r.label, r.eligible])),
    '',
    sectionFlags(limits.flags),
    '',
  ].join('\n');

  return { flags, markdown: md };
}

/** A tiny text bar; 1.0 means "at the flag line". */
function bar(ratio: number): string {
  const width = 10;
  const filled = Math.max(0, Math.min(width, Math.round(ratio * width)));
  return '`' + '█'.repeat(filled) + '·'.repeat(width - filled) + '`';
}
